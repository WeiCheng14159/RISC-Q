"""PynqDriver: the 4-method Driver over the ZCU216 AXI window + the RFDC bring-up ops.
The ONLY module that imports pynq/xrfclk/xrfdc — it only ever runs on the board;
the server imports it lazily inside load(). The RFDC operations are reproduced from two working
references — QubiC's PLInterface and qcal-riscq's RiscqPlInterface (this gateware's previous
driver, same board) — and stay unverified until M6 hardware bring-up."""

from __future__ import annotations

import asyncio
import json
import logging
import re
from pathlib import Path

import numpy as np
import pynq
import xrfclk
import xrfdc  # noqa: F401 — registers the RFdc driver so overlay.rf_data_converter binds

log = logging.getLogger(__name__)

AXI_BASE = 0x8000_0000   # riscvsoc-bd flow: bd-build.tcl assign_bd_address -offset
AXI_SIZE = 0x1000_0000   # ... -range

# board.json defaults; tile/block keys are "tile,block" strings. "board" picks the RF clock plan's board
# (default ZCU216); the clock keys (lmk_file / lmx_file / ref_tile / mts_tiles / mts) default from it.
BOARD_DEFAULTS = {
    "adc_nyquist": 1,
    "dac_nyquist": {"default": 2},
    "dac_current": {},
}
DEFAULT_BOARD = "ZCU216"

# TICS Pro register exports bundled with the driver, one folder per board, generated by opentics
# from the board's own TICS Pro projects; clocks/<board>/opentics.toml regenerates them.
CLOCK_ROOT = Path(__file__).with_name("clocks")

# RISC-Q's native rates: dspClk 500 MHz, so DAC 8 GS/s (16 samples/cycle) and ADC 2 GS/s (4/cycle).
# On both boards the LMK04828 makes the 500 MHz PL_CLK (CLKout8), 250 MHz for the LMX2594s and a
# 10 MHz PL/RF SYSREF from a 3000 MHz VCO; both LMX2594s turn 250 MHz into a 500 MHz reference
# (VCO 8 GHz / 16), and the plan's ref tile multiplies it in its PLL (x16 DAC, x4 ADC) and distributes
# the sample clock to the other tiles. The bitstream side is vivado-scripts/riscvsoc-bd/inc/
# clock-plan.tcl (same plan name, same ref tile). MTS targets stay None (free sync, latencies
# reported) until a board measurement pins them in board.json "mts".
_NATIVE_FILES = {"lmk_file": "LMK04828_10.0_250.0_500.0_10.0.txt", "lmx_file": "LMX2594_250.0_500.0.txt"}
CLOCK_PLANS = {
    # The CLK104's LMX2594 outputs reach ADC 225 / DAC 229: tile 1 refs and distributes; all 4x4 used.
    "ZCU216": {
        500e6: {"plan": "native", **_NATIVE_FILES, "ref_tile": 1, "mts_tiles": 0b1111,
                "mts": {"daclatency": None, "adclatency": None}},
    },
    # Only tiles 0 and 2 are bonded out (ADC 224/226, DAC 228/230); tile 2 refs and distributes.
    "RFSoC4x2": {
        500e6: {"plan": "native", **_NATIVE_FILES, "ref_tile": 2, "mts_tiles": 0b0101,
                "mts": {"daclatency": None, "adclatency": None}},
    },
}


def clock_plan(dsp_freq_hz: float, board: str = DEFAULT_BOARD) -> dict:
    """The RF clock plan for a board and a build's dspClk frequency (a copy — callers overlay
    board.json). `clock_dir` is where the plan's TICS files live."""
    if board not in CLOCK_PLANS:
        raise ValueError(f"no RF clock plans for board {board!r} (known: {sorted(CLOCK_PLANS)})")
    for freq, plan in CLOCK_PLANS[board].items():
        if abs(freq - dsp_freq_hz) < 1.0:
            return {**plan, "mts": dict(plan["mts"]), "board": board,
                    "clock_dir": str(CLOCK_ROOT / board)}
    raise ValueError(f"no RF clock plan for dsp_freq_hz={dsp_freq_hz:g} on {board} "
                     f"(known: {sorted(CLOCK_PLANS[board])})")


def read_tics(path: Path) -> list[int]:
    """Register words of a TICS Pro hex export (`Rn\t0xVVVVVV` per line), in file order."""
    return [int(line.split("\t")[-1], 16) for line in Path(path).read_text().splitlines() if line.strip()]


_refclks_done = False    # LMK/LMX setup runs once per server process, not per load


class PynqDriver:
    """MMIO Driver + overlay + RFDC ops. Construction IS bring-up, in the reference order:
    ref clocks -> overlay download -> MMIO -> MTS -> Nyquist zones -> DAC VOP."""

    def __init__(self, xsa: str, params_json: str, board: dict | None = None,
                 download: bool = True):
        # pynq's Xrt-backed EmbeddedDevice does `asyncio.get_event_loop()` when it is first
        # constructed (XrtDevice.__init__, triggered by the Overlay below). The board server
        # runs load() in a Pyro5 worker thread, which on Python 3.10+ has no implicit loop — give
        # it one so the probe doesn't raise "no current event loop in thread ...". We never run
        # the loop (the driver polls, it never waits on interrupts); the probe just needs the
        # call to succeed. No-op on the main thread, which already has a loop.
        try:
            asyncio.get_event_loop()
        except RuntimeError:
            asyncio.set_event_loop(asyncio.new_event_loop())

        self.params_text = Path(params_json).read_text()
        dsp_freq_hz = float(json.loads(self.params_text)["dsp_freq_hz"])
        board_name = (board or {}).get("board", DEFAULT_BOARD)
        cfg = {**BOARD_DEFAULTS, **clock_plan(dsp_freq_hz, board_name), **(board or {})}
        self.cfg = cfg
        self.ref_tile = int(cfg["ref_tile"])
        log.info(f"RF clock plan {cfg['plan']} on {cfg['board']} (dsp {dsp_freq_hz / 1e6:g} MHz, "
                 f"ref tile {self.ref_tile})")

        global _refclks_done
        if not _refclks_done:
            self.program_clock_files(cfg["lmk_file"], cfg["lmx_file"])
            _refclks_done = True
        overlay_file = _overlay_file(xsa)
        log.info(f"loading overlay: {overlay_file}")
        # ignore_version: PYNQ 2.7's xrfdc binds only usp_rf_data_converter 2.3/2.4, and a Vivado
        # 2023.1 build emits 2.6 — without it the RFDC comes up as DefaultIP (no mts_*/tiles). The
        # register map the driver uses is unchanged across these versions; SPEAR's ZCU216 overlays
        # (rfsoc_lib/rfsoc_overlay.py) load the same way on zcu216-0.
        self.overlay = pynq.Overlay(overlay_file, download=download, ignore_version=True)
        self.rfdc = self.overlay.rf_data_converter
        self.mmio = pynq.MMIO(AXI_BASE, AXI_SIZE)

        # Auto-MTS is opt-out and non-fatal: board.json "mts": null skips it at bring-up (run
        # drv.board.mts() by hand instead; mts_result stays None = "not run"), and a hard MTS
        # miss with it enabled is logged + surfaced via info(), never aborts load().
        if cfg["mts"]:
            try:
                self.mts_result = self.mts(**cfg["mts"])
            except RuntimeError as e:
                log.error(f"auto-MTS failed, continuing (set board.json \"mts\": null to skip): {e}")
                self.mts_result = 1
        else:
            self.mts_result = None
        log.info(f"mts: {self.mts_result}")
        zones = cfg["dac_nyquist"]
        for tile in range(4):
            for block in range(4):
                self.dac_nyquist_zone(tile, block,
                                      zones.get(f"{tile},{block}", zones.get("default", 2)))
        self.adc_nyquist_zone(cfg["adc_nyquist"])
        for tileblock, uA in cfg["dac_current"].items():
            tile, block = (int(x) for x in tileblock.split(","))
            self.dacvop(tile, block, uA)

        # ── host-window result buffer ──
        # One contiguous CMA buffer, 16 MB per core, allocated ONCE for the session: the PL writes
        # results straight into it over S_AXI_HP0_FPD, so a raw run is no longer bounded by the
        # core's 16 KB RAM and readback is a numpy copy instead of word-at-a-time MMIO.
        # `pynq.allocate` is non-cacheable by default, so a read sees DDR with no cache maintenance.
        from riscq.map import SocMap, SocParams
        nbytes = SocMap(SocParams.from_json(self.params_text)).hostwin_bytes_total
        _check_cma(nbytes)
        self._host_buf = pynq.allocate(shape=(nbytes,), dtype=np.uint8)
        self.host_base = int(self._host_buf.device_address)
        log.info(f"host window: {nbytes / (1 << 20):.0f} MB at {self.host_base:#x}")

    # ── the Driver protocol over pynq.MMIO (a numpy uint32 view of the /dev/mem mmap) ──

    def _check(self, addr: int, nbytes: int = 4) -> None:
        if addr % 4:
            raise ValueError(f"unaligned address {addr:#x}")
        if addr < 0 or addr + nbytes > AXI_SIZE:
            raise ValueError(f"[{addr:#x}, {addr + nbytes:#x}) outside the AXI window "
                             f"(size {AXI_SIZE:#x})")

    def read32(self, addr: int) -> int:
        self._check(addr)
        return self.mmio.read(addr)

    def write32(self, addr: int, value: int) -> None:
        self._check(addr)
        self.mmio.write(addr, int(value) & 0xFFFFFFFF)

    def read_block(self, addr: int, nbytes: int) -> bytes:
        self._check(addr, nbytes)
        # Word-at-a-time single-beat reads (like read32/write_block). A numpy slice read
        # (self.mmio.array[a:b].tobytes()) issues a multi-beat/wide AXI burst that this gateware's
        # BRAM host read port DECERRs -> SIGBUS ("Bus error"); the PL only handles 32-bit beats.
        nwords = -(-nbytes // 4)
        buf = b"".join((self.mmio.read(addr + 4 * i) & 0xFFFFFFFF).to_bytes(4, "little")
                       for i in range(nwords))
        return buf[:nbytes]

    def close(self) -> None:
        """Release the CMA result buffer. Called before a reload so the next driver's
        `pynq.allocate` sees the pool free."""
        buf, self._host_buf = getattr(self, "_host_buf", None), None
        if buf is not None:
            buf.freebuffer()

    def read_host(self, offset: int, nbytes: int) -> bytes:
        """Read the CMA result buffer at buffer-relative `offset`. Only
        valid after the program's DONE — the window writes are posted."""
        if not 0 <= offset <= self._host_buf.nbytes - nbytes:
            raise ValueError(f"read_host [{offset}, {offset + nbytes}) outside the "
                             f"{self._host_buf.nbytes} B host buffer")
        view = self._host_buf[offset:offset + nbytes]
        invalidate = getattr(self._host_buf, "invalidate", None)
        if invalidate is not None:
            invalidate()      # no-op on a non-cacheable buffer; correct if one is ever cacheable
        return view.tobytes()

    def write_block(self, addr: int, data: bytes) -> None:
        data = bytes(data)
        if len(data) % 4:
            raise ValueError(f"write_block length {len(data)} is not a multiple of 4 "
                             "(pynq MMIO word-loops the payload)")
        self._check(addr, len(data))
        self.mmio.write(addr, data)

    # ── RFDC ops, reproduced verbatim from the references ──

    def refclks(self, lmk_freq: float, lmx_freq: float | None = None) -> None:
        if lmx_freq is None:
            xrfclk.set_ref_clks(lmk_freq=lmk_freq)
        else:
            xrfclk.set_ref_clks(lmk_freq=lmk_freq, lmx_freq=lmx_freq)
        log.info(f"ref clocks: lmk={lmk_freq} lmx={lmx_freq}")

    def program_clock_files(self, lmk_file: str, lmx_file: str) -> None:
        """Program the LMK04828 and both LMX2594s from TICS register exports (bare names resolve in
        the plan's clock_dir, clocks/<board>/) with the raw SPI writes xrfclk itself uses, so no
        file has to be installed into the board's xrfclk package."""
        clock_dir = Path((getattr(self, "cfg", None) or {}).get("clock_dir") or CLOCK_ROOT / DEFAULT_BOARD)
        lmk_path, lmx_path = (Path(f) if Path(f).is_absolute() else clock_dir / f
                              for f in (lmk_file, lmx_file))
        lmk_regs, lmx_regs = read_tics(lmk_path), read_tics(lmx_path)
        if len(lmx_regs) != 113:
            raise ValueError(f"{lmx_path.name}: an LMX2594 export has 113 registers, got {len(lmx_regs)}")
        xc = xrfclk.xrfclk
        if not xc.lmk_devices and not xc.lmx_devices:
            xc._find_devices()
        for dev in xc.lmk_devices:          # LMK first: it is the LMXs' reference
            xc._write_LMK_regs(lmk_regs, dev)
        for dev in xc.lmx_devices:
            xc._write_LMX_regs(lmx_regs, dev)
        log.info(f"ref clocks: {lmk_path.name} -> {len(xc.lmk_devices)} LMK, "
                 f"{lmx_path.name} -> {len(xc.lmx_devices)} LMX")

    def config_mts(self, daclatency: int = -1, adclatency: int = -1) -> None:
        for mts_cfg in (self.rfdc.mts_dac_config, self.rfdc.mts_adc_config):
            mts_cfg.RefTile = self.ref_tile   # the distributing tile (clock plan)
            mts_cfg.Tiles = int((getattr(self, "cfg", None) or {}).get("mts_tiles", 0xF))  # tiles to sync
            mts_cfg.SysRef_Enable = 1
        self.rfdc.mts_dac_config.Target_Latency = daclatency
        self.rfdc.mts_adc_config.Target_Latency = adclatency

    def mts(self, daclatency: int | None = None, adclatency: int | None = None) -> int:
        """Two-pass MTS (QubiC): free sync to measure the latencies; if all tiles agree and are
        within target, re-sync pinned to the targets. 0 iff every measured latency == target.
        A target of None takes the clock plan's (board.json "mts"); a plan with no measured targets
        stops after the free sync and returns 0 iff all tiles of each kind agree.
        Raises (XRFdc_MultiConverter_Sync) if a tile never reaches the started state — run it by
        hand via drv.board.mts() to see the full converter error; __init__ guards the auto call
        so an MTS miss never aborts bring-up (MTS is re-pinned at bring-up)."""
        plan = (getattr(self, "cfg", None) or {}).get("mts") or {}
        daclatency = plan.get("daclatency") if daclatency is None else daclatency
        adclatency = plan.get("adclatency") if adclatency is None else adclatency
        self.config_mts()
        self.rfdc.mts_dac()
        self.rfdc.mts_adc()
        dac_lat, adc_lat = self._mts_latencies()
        self.mts_latencies = {"dac": dac_lat, "adc": adc_lat}
        log.info(f"mts free sync: dac={dac_lat} adc={adc_lat}")
        if daclatency is None or adclatency is None:
            return 0 if (len(set(dac_lat)) == 1 and len(set(adc_lat)) == 1) else 1
        if (all(l == dac_lat[0] for l in dac_lat) and dac_lat[0] <= daclatency
                and all(l == adc_lat[0] for l in adc_lat) and adc_lat[0] <= adclatency):
            self.config_mts(daclatency, adclatency)
            self.rfdc.mts_dac()
            self.rfdc.mts_adc()
            dac_lat, adc_lat = self._mts_latencies()
            self.mts_latencies = {"dac": dac_lat, "adc": adc_lat}
            log.info(f"mts pinned: dac={dac_lat} adc={adc_lat}")
        return 0 if (all(l == daclatency for l in dac_lat)
                     and all(l == adclatency for l in adc_lat)) else 1

    def _mts_latencies(self) -> tuple[list, list]:
        return ([self.rfdc.mts_dac_config.Latency[i] for i in range(4)],
                [self.rfdc.mts_adc_config.Latency[i] for i in range(4)])

    def rf_status(self) -> dict:
        """Per-tile RFDC readback, to print before trusting any data: IPStatus State (15 = running),
        PowerUpState, PLLState, the tile's PLLLockStatus (xrfdc: 1 = unlocked, 2 = locked; only the
        plan's ref tile runs a PLL, the others take its distributed clock) and ClockSource."""
        ip = self.rfdc.IPStatus
        out = {}
        for kind, tiles, key in (("dac", self.rfdc.dac_tiles, "DACTileStatus"),
                                 ("adc", self.rfdc.adc_tiles, "ADCTileStatus")):
            rows = []
            for t in range(4):
                st = ip[key][t]
                row = {k: int(st[k]) for k in ("TileState", "PowerUpState", "PLLState", "BlockStatusMask")
                       if k in st}
                for prop in ("PLLLockStatus", "ClockSource"):
                    try:
                        row[prop] = int(getattr(tiles[t], prop))
                    except Exception as e:      # a tile without a PLL may refuse the query
                        row[prop] = f"err: {e}"
                rows.append(row)
            out[kind] = rows
        out["state"] = int(ip.get("State", -1))
        return out

    def adc_nyquist_zone(self, n: int) -> None:
        for tile in range(4):        # rfdc-config.tcl enables every slice: full 4x4
            for block in range(4):
                self.rfdc.adc_tiles[tile].blocks[block].NyquistZone = n

    def dac_nyquist_zone(self, tile: int, block: int, n: int) -> None:
        self.rfdc.dac_tiles[tile].blocks[block].NyquistZone = n

    def dacvop(self, tile: int, block: int, uA: int) -> None:
        log.info(f"dac vop: tile {tile} block {block} -> {uA} uA")
        self.rfdc.dac_tiles[tile].blocks[block].SetDACVOP(uA)


def _overlay_file(xsa: str) -> str:
    """The file to hand pynq.Overlay. PYNQ 3 loads the bundle's .xsa directly; PYNQ 2.x only takes
    a .bit with a same-named .hwh beside it, so there the bundle must also carry top.bit + top.hwh
    (both are inside the .xsa — Vivado writes them next to it too)."""
    xsa = Path(xsa)
    if int(pynq.__version__.split(".")[0]) >= 3:
        return str(xsa)
    bit, hwh = xsa.with_suffix(".bit"), xsa.with_suffix(".hwh")
    if not (bit.exists() and hwh.exists()):
        raise FileNotFoundError(
            f"PYNQ {pynq.__version__} cannot load an .xsa: put {bit.name} and {hwh.name} "
            f"next to {xsa.name} in {xsa.parent}")
    return str(bit)


def _check_cma(nbytes: int) -> None:
    """Fail loudly and early if the kernel's CMA pool cannot hold the result buffer — otherwise
    `pynq.allocate` dies deep in the driver with an opaque error. Fix by
    rebuilding with a narrower window (`"hostwin_bits": 23` in the build JSON) or rebuilding the
    image with a larger `cma=` boot arg."""
    try:
        info = Path("/proc/meminfo").read_text()
    except OSError:
        return                     # not Linux/procfs — let allocate() speak for itself
    fields = {k: int(v) * 1024 for k, v in re.findall(r"^(Cma\w+):\s+(\d+) kB", info, re.M)}
    total, free = fields.get("CmaTotal"), fields.get("CmaFree")
    if total is None:
        return
    if total < nbytes or (free is not None and free < nbytes):
        raise RuntimeError(
            f"host-window buffer needs {nbytes / (1 << 20):.0f} MB of CMA, but CmaTotal="
            f"{total / (1 << 20):.0f} MB / CmaFree={(free or 0) / (1 << 20):.0f} MB. Rebuild with a "
            f"smaller `hostwin_bits` in the build JSON, boot with a larger `cma=`, or restart the "
            f"server to free a leaked buffer.")
